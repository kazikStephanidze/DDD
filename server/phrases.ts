export type PhraseCategory = keyof typeof PHRASE_POOLS;

export function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * Picks a phrase from a 40-item category without repeating recently shown ones in the chat.
 */
export function pickNonRepeatingPhrase(
  category: PhraseCategory,
  recentKeys: string[]
): { text: string; key: string } {
  const pool = PHRASE_POOLS[category];
  const recentForCategory = recentKeys.filter((k) => k.startsWith(`${category}:`));
  const recentSet = new Set(recentForCategory);

  const availableIndices: number[] = [];
  for (let i = 0; i < pool.length; i++) {
    if (!recentSet.has(`${category}:${i}`)) {
      availableIndices.push(i);
    }
  }

  // If all 40 in this category were recently used, pick any except the very last one
  if (availableIndices.length === 0) {
    const lastKey = recentForCategory[recentForCategory.length - 1];
    const lastIdx = lastKey ? parseInt(lastKey.split(':')[1], 10) : -1;
    for (let i = 0; i < pool.length; i++) {
      if (i !== lastIdx) availableIndices.push(i);
    }
  }

  const chosenIndex =
    availableIndices.length > 0 ? pickRandom(availableIndices) : Math.floor(Math.random() * pool.length);

  return {
    text: pool[chosenIndex],
    key: `${category}:${chosenIndex}`
  };
}

const TRIGGER_WORD_CHAR_RE = /[\p{L}\p{N}-]/u;

export function findChatTriggerMatch(text: string): string | null {
  const lower = text.toLowerCase();
  let bestIdx = Infinity;
  let bestKw = '';

  for (const kw of CHAT_TRIGGER_KEYWORDS) {
    const idx = lower.indexOf(kw);
    if (idx === -1) continue;
    if (idx < bestIdx || (idx === bestIdx && kw.length > bestKw.length)) {
      bestIdx = idx;
      bestKw = kw;
    }
  }

  if (!bestKw) return null;

  let start = bestIdx;
  let end = bestIdx + bestKw.length;
  while (start > 0 && TRIGGER_WORD_CHAR_RE.test(lower[start - 1])) start--;
  while (end < lower.length && TRIGGER_WORD_CHAR_RE.test(lower[end])) end++;

  const extracted = text.slice(start, end).trim().replace(/^-+|-+$/g, '');
  const result = (extracted || bestKw).toLowerCase();
  return result.length > 36 ? `${result.slice(0, 36)}…` : result;
}

export function matchesChatTrigger(text: string): boolean {
  return findChatTriggerMatch(text) !== null;
}

export function getPhraseCatalogStats() {
  const categories = Object.entries(PHRASE_POOLS).map(([key, list]) => ({
    key,
    count: list.length
  }));
  const totalUniquePhrases = categories.reduce((sum, c) => sum + c.count, 0);
  const minPerCategory = Math.min(...categories.map((c) => c.count));

  return {
    categoriesCount: categories.length,
    phrasesPerCategory: minPerCategory,
    totalUniquePhrases,
    triggerKeywordsCount: CHAT_TRIGGER_KEYWORDS.length
  };
}
